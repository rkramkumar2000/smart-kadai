  var n = 0;
  Product make(
    String slug,
    String en,
    String ta,
    String tanglish,
    String category,
    Unit stockUnit,
    double pricePerStockUnit,
    List<(Unit, double, double, double?)> variants, {
    String brand = '',
    double minStock = 0,
    double stock = 0,
  }) {
    n++;
    final id = 'p-$slug';
    var i = 0;
    final vs = variants.map((v) {
      final (unit, qty, price, factor) = v;
      final f =
          factor ?? ProductVariant.autoStockFactor(unit, qty, stockUnit) ?? 1;
      final variant = ProductVariant(
        id: '$id-v$i',
        productId: id,
        unit: unit,
        quantity: qty,
        stockFactor: f,
        sellingPrice: price,
        purchasePrice: (price * 0.85 * 100).roundToDouble() / 100,
        isDefault: i == 0,
        sort: i,
      );
      i++;
      return variant;
    }).toList();
    return Product(
      id: id,
      code: 'P${n.toString().padLeft(4, '0')}',
      nameEn: en,
      nameTa: ta,
      nameTanglish: tanglish,
      category: category,
      brand: brand,
      stockUnit: stockUnit,
      sellingPrice: pricePerStockUnit,
      purchasePrice: (pricePerStockUnit * 0.85 * 100).roundToDouble() / 100,
      minStock: minStock,
      stockQty: stock,
      createdAt: now,
      updatedAt: now,
      variants: vs,
    );
  }

